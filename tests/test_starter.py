"""End-to-end checks using temporary outputs; original practice data stays intact."""
import json
import os
from pathlib import Path
import subprocess
import sys
import tempfile
import unittest

import joblib
import numpy as np
import pandas as pd
from streamlit.testing.v1 import AppTest

from scripts.train_baseline import get_parts

ROOT = Path(__file__).resolve().parents[1]


class StarterChecks(unittest.TestCase):
    def setUp(self):
        self.temp = tempfile.TemporaryDirectory()
        self.addCleanup(self.temp.cleanup)
        self.out = Path(self.temp.name)

    def run_script(self, script, *args, succeeds=True):
        result = subprocess.run(
            [sys.executable, str(ROOT / 'scripts' / script), *map(str, args)],
            cwd=ROOT, capture_output=True, text=True, timeout=120,
            env={**os.environ, 'MPLBACKEND': 'Agg'},
        )
        if succeeds:
            self.assertEqual(result.returncode, 0, result.stdout + result.stderr)
        else:
            self.assertNotEqual(result.returncode, 0)
        return result

    def test_profile_outputs_and_invalid_target(self):
        self.run_script('profile_data.py', '--data', 'data/mock_water_network.csv',
                        '--target', 'failed_next_30d', '--out', self.out / 'profile')
        summary = (self.out / 'profile/summary.txt').read_text()
        self.assertIn('Rows: 1512', summary)
        self.assertIn('Exact duplicated rows: 12', summary)
        self.assertEqual(len(pd.read_csv(self.out / 'profile/column_profile.csv')), 14)
        result = self.run_script('profile_data.py', '--data', 'data/mock_water_network.csv',
                                 '--target', 'not_a_column', '--out', self.out / 'bad',
                                 succeeds=False)
        self.assertIn('not_a_column', result.stderr)
        self.assertFalse((self.out / 'bad').exists())

    def test_water_baseline_and_training_only_imputation(self):
        self.run_script('train_baseline.py', '--data', 'data/mock_water_network.csv',
                        '--target', 'failed_next_30d', '--drop', 'pipe_id',
                        'repair_cost_after_event_inr', '--time-col', 'inspection_date',
                        '--out', self.out)
        report = json.loads((self.out / 'metrics.json').read_text())
        self.assertEqual([report[k] for k in ('n_train', 'n_validation', 'n_test')],
                         [900, 300, 300])
        self.assertEqual(report['target_classes'], {'0': '0', '1': '1'})
        self.assertNotIn('repair_cost_after_event_inr', report['features'])
        self.assertGreater(report['model_test']['average_precision_pr_auc'],
                           report['dummy_test']['average_precision_pr_auc'])
        self.assertTrue((self.out / 'confusion_matrix.png').is_file())
        predictions = pd.read_csv(self.out / 'test_predictions.csv')
        self.assertEqual(len(predictions), 300)
        self.assertEqual(int(predictions['selected_for_inspection'].sum()), 30)
        # Inspect only the artifact just generated by this test.
        model = joblib.load(self.out / 'model.joblib')
        clean = pd.read_csv(ROOT / 'data/mock_water_network.csv').drop_duplicates()
        train, _, _ = get_parts(clean, 'failed_next_30d', 'classification',
                                 'inspection_date', 42)
        numeric = model.named_steps['preprocessor'].transformers_[0][2]
        fitted = model.named_steps['preprocessor'].named_transformers_['num'].statistics_
        np.testing.assert_allclose(fitted, train[numeric].median().to_numpy())

    def test_delivery_regression(self):
        self.run_script('train_baseline.py', '--data', 'data/mock_delivery_times.csv',
                        '--target', 'delivery_minutes', '--drop', 'order_id',
                        'customer_review_after_delivery', '--time-col', 'order_placed_date',
                        '--out', self.out)
        report = json.loads((self.out / 'metrics.json').read_text())
        self.assertEqual(report['task'], 'regression')
        self.assertLess(report['model_test']['rmse'], report['dummy_test']['rmse'])
        self.assertEqual(len(pd.read_csv(self.out / 'test_predictions.csv')), 260)

    def test_leakage_column_is_rejected(self):
        result = self.run_script('train_baseline.py', '--data', 'data/mock_water_network.csv',
                                 '--target', 'failed_next_30d', '--out', self.out,
                                 succeeds=False)
        self.assertIn('POSSIBLE TARGET LEAKAGE', result.stderr)
        self.assertFalse((self.out / 'model.joblib').exists())

    def test_one_class_split_is_rejected_before_fit(self):
        data = pd.DataFrame({'date': pd.date_range('2026-01-01', periods=60),
                             'value': np.arange(60), 'target': [0] * 36 + [1] * 24})
        path = self.out / 'one_class.csv'
        data.to_csv(path, index=False)
        result = self.run_script('train_baseline.py', '--data', path, '--target', 'target',
                                 '--time-col', 'date', '--out', self.out, succeeds=False)
        self.assertIn('train split has only one class', result.stderr)
        self.assertFalse((self.out / 'model.joblib').exists())

    def test_chronological_split_preserves_existing_sort_date_column(self):
        data = pd.DataFrame({'when': pd.date_range('2026-01-01', periods=50)[::-1],
                             '_sort_date': np.arange(50), 'target': [0, 1] * 25})
        original = data.copy(deep=True)
        train, valid, test = get_parts(data, 'target', 'classification', 'when', 42)
        self.assertLess(train.when.max(), valid.when.min())
        self.assertLess(valid.when.max(), test.when.min())
        self.assertEqual(len(set(train.index) | set(valid.index) | set(test.index)), 50)
        pd.testing.assert_frame_equal(data, original)
        pd.testing.assert_series_equal(pd.concat([train, valid, test])['_sort_date'].sort_index(),
                                       original['_sort_date'])

    def test_generators_preserve_expected_synthetic_data(self):
        # Redirect generation to temp files so tests never overwrite supplied datasets.
        from scripts import generate_mock_data, generate_mock_regression
        for module, name in [(generate_mock_data, 'mock_water_network.csv'),
                             (generate_mock_regression, 'mock_delivery_times.csv')]:
            original = module.OUT
            try:
                module.OUT = self.out / name
                module.main()
                pd.testing.assert_frame_equal(pd.read_csv(module.OUT),
                                               pd.read_csv(ROOT / 'data' / name))
            finally:
                module.OUT = original

    def test_dashboard_default_and_empty_filter(self):
        app = AppTest.from_file(str(ROOT / 'app.py')).run(timeout=30)
        self.assertEqual(len(app.exception), 0, str(app.exception))
        self.assertEqual(app.metric[0].value, '1,512')
        category_filter = next(box for box in app.selectbox
                               if box.label == 'Filter by category')
        category_filter.select('district').run(timeout=30)
        self.assertEqual(len(app.exception), 0, str(app.exception))
        app.multiselect[0].set_value([]).run(timeout=30)
        self.assertEqual(len(app.exception), 0, str(app.exception))


if __name__ == '__main__':
    unittest.main()
